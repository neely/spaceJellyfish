// Finds the GOES ABI CONUS pixel nearest each cloud station and pins it in
// data/goes/station-pixels.json. Reads NOAA STAR's precomputed GOES-19 CONUS
// latitude and longitude file (config/goes-acm.json, grid), so this project
// does not code the projection formula.
//
//   node scripts/goes-station-pixels.js <path to goes19_abi_conus_lat_lon.nc>
//
// Stops if the file's SHA-256 does not match the config.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { openH5, nearestPixel } from './lib/goes.js';

const root = new URL('../', import.meta.url);
const goes = JSON.parse(await readFile(new URL('config/goes-acm.json', root)));
const stations = JSON.parse(await readFile(new URL('config/cloud-stations.json', root))).stations;

const path = process.argv[2];
if (!path) throw new Error('usage: node scripts/goes-station-pixels.js <grid .nc>');
const sha = createHash('sha256').update(await readFile(path)).digest('hex');
if (sha !== goes.grid.ncSha256) throw new Error(`grid SHA-256 ${sha} does not match config/goes-acm.json`);

const f = await openH5(path);
const [rows, cols] = f.get('latitude').shape;
const lat = f.get('latitude').value;
const lon = f.get('longitude').value;

const out = {};
for (const [id, st] of Object.entries(stations)) {
  const p = nearestPixel(lat, lon, cols, st.latitudeDeg, st.longitudeDeg);
  if (!p) throw new Error(`${id}: no pixel within 0.1 degrees`);
  out[id] = { row: p.row, col: p.col, pixelLatDeg: +lat[p.i].toFixed(5), pixelLonDeg: +lon[p.i].toFixed(5), offsetKm: +p.km.toFixed(3) };
}

await mkdir(new URL('data/goes/', root), { recursive: true });
await writeFile(new URL('data/goes/station-pixels.json', root), JSON.stringify({
  about: 'Generated by scripts/goes-station-pixels.js. Row and column of the ABI CONUS pixel nearest each station (0-based, row 0 is north). Do not edit by hand.',
  grid: { file: goes.grid.file, ncSha256: sha, rows, cols },
  stations: out,
}, null, 2) + '\n');
console.log(out);
