// Satellite check, step 1: scores the GOES Clear Sky Mask against the
// airport reports, with the same cloudy class and skill as
// scripts/score-clouds.js. Reads only pinned files: data/goes/acm-stations.json,
// data/goes/station-pixels.json and data/clouds/raw/. Rules: config/goes-acm.json.
// Writes clouds/goes-results.json and clouds/goes-results.md.
//
//   node scripts/score-goes.js
import { readFile, writeFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { parseIemCsv, reportsByHour, reportCoverPct, sunElevationDeg, score, ASOS_LIMIT_FT } from './lib/clouds.js';
import { boxCloudyPct } from './lib/goes.js';

const root = new URL('../', import.meta.url);
const clouds = JSON.parse(await readFile(new URL('config/cloud-stations.json', root)));
const goes = JSON.parse(await readFile(new URL('config/goes-acm.json', root)));
const extract = JSON.parse(await readFile(new URL('data/goes/acm-stations.json', root)));
const manifest = JSON.parse(await readFile(new URL('data/clouds/manifest.json', root)));
const forecastResults = JSON.parse(await readFile(new URL('clouds/results.json', root)));
const raw = async (name) => {
  const buf = gunzipSync(await readFile(new URL(`data/clouds/raw/${name}`, root)));
  const sha = createHash('sha256').update(buf).digest('hex');
  if (sha !== manifest.files[name].sha256) throw new Error(`${name}: SHA-256 does not match the manifest`);
  return buf.toString('utf8');
};

const CLOUDY = clouds.cloudyPct;
const v = goes.variable.toLowerCase();
const scans = extract.scans;
const satOf = (key) => /_G(\d+)_/.exec(key)[1];

const pairs = {}; // pairs[truth][subset] = [[maskPct, observedPct], ...]
const push = (truth, sub, pair) => ((pairs[truth] ??= {})[sub] ??= []).push(pair);
const dropped = { noReport: 0, noScan: 0, fewGoodPixels: 0, unknownCode: 0 };

for (const { kind, hourMs } of extract.hours) {
  for (const [id, st] of Object.entries(clouds.stations)) {
    const reports = (pairs._reports ??= {});
    reports[id] ??= reportsByHour(parseIemCsv(await raw(`${id}-iem.csv.gz`)));
    const r = reports[id].get(hourMs);
    if (!r) { dropped.noReport++; continue; }
    let best = null;
    for (const s of scans) if (!best || Math.abs(s.midMs - r.timeMs) < Math.abs(best.midMs - r.timeMs)) best = s;
    if (!best || Math.abs(best.midMs - r.timeMs) > goes.maxMatchMinutes * 60e3) { dropped.noScan++; continue; }
    const box = best.stations[id];
    const { pct } = boxCloudyPct(box[v], box.dqf, goes.goodDqf, goes.minGoodPixels);
    if (pct == null) { dropped.fewGoodPixels++; continue; }
    const below12 = reportCoverPct(r.layers, ASOS_LIMIT_FT);
    const all = reportCoverPct(r.layers);
    if (below12 == null) { dropped.unknownCode++; continue; }
    const sun = sunElevationDeg(st, hourMs);
    const light = sun >= clouds.twilightSunDeg.min && sun <= clouds.twilightSunDeg.max ? 'twilight' : sun > clouds.twilightSunDeg.max ? 'day' : 'night';
    const subsets = ['all', light, `G${satOf(best.key)}`, `${light}-G${satOf(best.key)}`, `picked-${kind}`];
    if (clouds.nearCharleston.includes(id)) subsets.push('nearCharleston', `${light}-nearCharleston`);
    // Sun between 0 and -3 degrees: the mask's own twilight region is solar
    // zenith 87 to 93 degrees (twilight_solar_zenith_angle_bounds in the files).
    if (light === 'twilight') subsets.push(sun >= -3 ? 'twilight-sun0to3' : 'twilight-sun3to18');
    for (const sub of subsets) push('below12000ft', sub, [pct, below12]);
    if (forecastResults.stations[id]?.fullSky) for (const sub of subsets) push('fullSky', sub, [pct, all]);
  }
}
delete pairs._reports;

const whole = (x) => (x == null ? null : Math.round(100 * x));
const results = {
  about: 'Generated by scripts/score-goes.js from data/goes/acm-stations.json and data/clouds/raw. Do not edit by hand.',
  inputs: { scans: scans.length, hours: extract.hours.length, fetched: extract.fetched },
  cloudyPct: CLOUDY,
  dropped,
  tests: {},
};
for (const [truth, subs] of Object.entries(pairs)) {
  results.tests[truth] = {};
  for (const [sub, p] of Object.entries(subs).sort()) {
    const sc = score(p, CLOUDY);
    results.tests[truth][sub] = { ...sc, skillPct: whole(sc.skill), hitPct: whole(sc.hitRate), falsePct: whole(sc.falseRate) };
  }
}
const g = goes.goNoGo;
const decisive = results.tests[g.truth]?.[g.subset];
const nbmDay1Twilight = forecastResults.tests.lead.below12000ft.twilight.ncep_nbm_conus['1'].skillPct;
results.goNoGo = {
  rule: `${g.truth}, ${g.subset}: skill at least ${g.minSkillPct}`,
  skillPct: decisive?.skillPct ?? null,
  n: decisive?.n ?? 0,
  nbmDay1TwilightSkillPct: nbmDay1Twilight,
  pass: decisive?.skillPct != null && decisive.skillPct >= g.minSkillPct,
};
await writeFile(new URL('clouds/goes-results.json', root), JSON.stringify(results, null, 1) + '\n');

let md = `# GOES Clear Sky Mask against airport reports (satellite check, step 1)\n\nGenerated by \`scripts/score-goes.js\`. Do not edit by hand. Method and reading: [README.md](README.md#satellite-check-step-1).\n\n`;
md += `${scans.length} scans for ${extract.hours.length} sample hours. Mask value: percent of good-quality ${goes.variable} pixels in a ${goes.boxPixels} by ${goes.boxPixels} box at the station. Cloudy means ${CLOUDY} percent or more, for the mask and for the airport. Skill is hit rate minus false-alarm rate. Pairs dropped: ${Object.entries(dropped).map(([k, n]) => `${k} ${n}`).join(', ')}.\n\n`;
md += `**Go/no-go** (${results.goNoGo.rule}): skill ${results.goNoGo.skillPct} on ${results.goNoGo.n} pairs, so **${results.goNoGo.pass ? 'go' : 'no-go'}**. NBM day-1 twilight skill against the same truth: ${nbmDay1Twilight}.\n`;
for (const [truth, subs] of Object.entries(results.tests)) {
  md += `\n## Truth: ${truth}\n\n| Subset | Pairs | Airport cloudy | Skill | Hit rate | False-alarm rate | MAE |\n|---|---|---|---|---|---|---|\n`;
  for (const [sub, s] of Object.entries(subs)) md += `| ${sub} | ${s.n} | ${s.cloudy} | ${s.skillPct} | ${s.hitPct} | ${s.falsePct} | ${s.mae.toFixed(1)} |\n`;
}
await writeFile(new URL('clouds/goes-results.md', root), md);
console.log(md);
