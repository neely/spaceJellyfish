// Satellite check, test 3 (land against water): pins the inputs that
// scripts/score-goes-relative.js reads. Rules: config/goes-relative.json.
// Three steps, run in order from a machine with normal internet access:
//
//   node scripts/fetch-goes-relative.js pixels <goes19_abi_conus_lat_lon.nc>
//        the 2 km GOES pixel nearest each water point -> data/goes/water-pixels.json
//   node scripts/fetch-goes-relative.js nbm
//        NBM past forecasts at the water points (Open-Meteo Previous Model
//        Runs, cell_selection=nearest) -> data/goes/water-nbm.json.gz
//   node scripts/fetch-goes-relative.js goes <scratch dir> [--recheck N]
//        for each twilight hour, the ACMC scan nearest the whole hour; the
//        5 by 5 BCM and DQF box at every airport and water point
//        -> data/goes/relative-acm.json. Whole files are deleted after use.
import { readFile, writeFile, mkdir, rm, access } from 'node:fs/promises';
import { gzipSync, gunzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { parseIemCsv, reportsByHour, sunElevationDeg } from './lib/clouds.js';
import { openH5, scanTimes, nearestPixel, distanceKm } from './lib/goes.js';

const root = new URL('../', import.meta.url);
const json = async (p) => JSON.parse(await readFile(new URL(p, root)));
const rel = await json('config/goes-relative.json');
const acmRules = await json('config/goes-acm.json');
const clouds = await json('config/cloud-stations.json');
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const [step, arg] = process.argv.slice(2);

if (step === 'pixels') {
  const sha = sha256(await readFile(arg));
  if (sha !== acmRules.grid.ncSha256) throw new Error(`grid SHA-256 ${sha} does not match config/goes-acm.json`);
  const f = await openH5(arg);
  const [rows, cols] = f.get('latitude').shape;
  const lat = f.get('latitude').value, lon = f.get('longitude').value;
  const out = {};
  for (const [id, [la, lo]] of Object.entries(rel.waterPoints.places)) {
    const p = nearestPixel(lat, lon, cols, la, lo);
    if (!p) throw new Error(`${id}: no pixel within 0.1 degrees`);
    out[id] = { row: p.row, col: p.col, pixelLatDeg: +lat[p.i].toFixed(5), pixelLonDeg: +lon[p.i].toFixed(5), offsetKm: +p.km.toFixed(3) };
  }
  await writeFile(new URL('data/goes/water-pixels.json', root), JSON.stringify({
    about: 'Generated by scripts/fetch-goes-relative.js pixels. Row and column of the ABI CONUS pixel nearest each water point (0-based, row 0 is north). Do not edit by hand.',
    grid: { file: acmRules.grid.file, ncSha256: sha, rows, cols },
    points: out,
  }, null, 2) + '\n');
  console.log(out);
} else if (step === 'nbm') {
  const { start, end } = clouds.period;
  const leads = rel.forecast.reportedLeadDays;
  const out = { requests: [], hourly: {} };
  const cells = new Set();
  for (const [id, [la, lo]] of Object.entries(rel.waterPoints.places)) {
    const url = `https://previous-runs-api.open-meteo.com/v1/forecast?latitude=${la}&longitude=${lo}` +
      `&hourly=${leads.map((d) => `cloud_cover_previous_day${d}`).join(',')}&models=${rel.forecast.model}` +
      `&start_date=${start}&end_date=${end}&timezone=GMT&cell_selection=nearest`;
    let j = null;
    for (let attempt = 1; attempt <= 3 && !j; attempt++) {
      const res = await fetch(url, { headers: { 'User-Agent': 'spacejellyfish cloud test (github.com/neely/spaceJellyfish)' } });
      const text = await res.text();
      if (res.ok) j = JSON.parse(text); else { console.error(`${id}: HTTP ${res.status} ${text.slice(0, 200)}`); await sleep(30000 * attempt); }
    }
    if (!j || j.error) throw new Error(`${id}: no answer`);
    // Cell checks (config/goes-relative.json, cellSelection).
    const km = distanceKm(la, lo, j.latitude, j.longitude);
    const cell = `${j.latitude},${j.longitude}`;
    if (km > 5) throw new Error(`${id}: cell ${cell} is ${km.toFixed(1)} km from the request`);
    if (j.elevation > 0) throw new Error(`${id}: cell elevation ${j.elevation} m`);
    if (cells.has(cell)) throw new Error(`${id}: cell ${cell} is shared with another water point`);
    cells.add(cell);
    out.requests.push({ id, url, latitude: j.latitude, longitude: j.longitude, elevation: j.elevation, offsetKm: +km.toFixed(2) });
    out.hourly.time ??= j.hourly.time;
    if (j.hourly.time.length !== out.hourly.time.length || j.hourly.time[0] !== out.hourly.time[0]) throw new Error(`${id}: hours do not match`);
    for (const [k, v] of Object.entries(j.hourly)) if (k !== 'time') out.hourly[`${k}_${id}`] = v;
    console.log(id, j.latitude, j.longitude, `${km.toFixed(2)} km`, `elevation ${j.elevation}`);
    await sleep(2000);
  }
  const text = JSON.stringify(out);
  await writeFile(new URL('data/goes/water-nbm.json.gz', root), gzipSync(text, { level: 9 }));
  await writeFile(new URL('data/goes/water-nbm.manifest.json', root), JSON.stringify({ fetched: new Date().toISOString(), bytes: Buffer.byteLength(text), sha256: sha256(text) }, null, 2) + '\n');
} else if (step === 'goes') {
  const scratch = arg;
  if (!scratch) throw new Error('usage: node scripts/fetch-goes-relative.js goes <scratch dir> [--recheck N]');
  await mkdir(scratch, { recursive: true });
  const OUT = new URL('data/goes/relative-acm.json', root);
  const stations = (await json('data/goes/station-pixels.json')).stations;
  const water = (await json('data/goes/water-pixels.json')).points;
  const boxes = { ...stations, ...water };
  const half = Math.floor(acmRules.boxPixels / 2);
  const WORKERS = 4;

  const download = async (s, w) => {
    const res = await fetch(`https://${s.bucket}.s3.amazonaws.com/${s.key}`);
    if (!res.ok) throw new Error(`${s.key}: HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length !== s.bytes) throw new Error(`${s.key}: ${buf.length} bytes, listing says ${s.bytes}`);
    const path = join(scratch, `rel${w}.nc`);
    await writeFile(path, buf);
    try {
      const f = await openH5(path);
      const box = {};
      for (const [id, p] of Object.entries(boxes)) {
        const sel = [[p.row - half, p.row + half + 1], [p.col - half, p.col + half + 1]];
        const str = (v) => Array.from(f.get(v).slice(sel), (x) => (x === 255 ? 'F' : String(x))).join('');
        box[id] = { bcm: str('BCM'), dqf: str('DQF') };
      }
      f.close();
      return { sha256: sha256(buf), boxes: box };
    } finally { await rm(path, { force: true }); }
  };
  const pool = async (items, fn) => {
    let next = 0;
    await Promise.all(Array.from({ length: WORKERS }, async (_, w) => { while (next < items.length) { const i = next++; await fn(items[i], w); } }));
  };

  const at = process.argv.indexOf('--recheck');
  if (at > 0) {
    const n = Number(process.argv[at + 1]);
    const pinned = JSON.parse(await readFile(OUT));
    const step = Math.max(1, Math.floor(pinned.scans.length / n));
    const pick = pinned.scans.filter((_, i) => i % step === 0).slice(0, n);
    let same = 0;
    await pool(pick, async (s, w) => {
      const got = await download(s, w);
      const ok = got.sha256 === s.sha256 && JSON.stringify(got.boxes) === JSON.stringify(s.boxes);
      console.log(ok ? 'same' : 'DIFFERENT', s.key); if (ok) same++;
    });
    console.log(`${same} of ${pick.length} rechecked scans are identical`);
    process.exit(same === pick.length ? 0 : 1);
  }

  // Twilight hours by the Sun at JZI (config/goes-relative.json, sample).
  const manifest = await json('data/clouds/manifest.json');
  const buf = gunzipSync(await readFile(new URL('data/clouds/raw/JZI-iem.csv.gz', root)));
  if (sha256(buf) !== manifest.files['JZI-iem.csv.gz'].sha256) throw new Error('JZI-iem.csv.gz: SHA-256 does not match');
  const jzi = clouds.stations.JZI;
  const hours = [...reportsByHour(parseIemCsv(buf.toString('utf8'))).keys()].sort((a, b) => a - b)
    .filter((h) => { const e = sunElevationDeg(jzi, h); return e >= clouds.twilightSunDeg.min && e <= clouds.twilightSunDeg.max; });
  // Keep the study period (UTC dates); the JZI file runs to the first hours of the next day.
  const inPeriod = hours.filter((h) => { const d = new Date(h).toISOString().slice(0, 10); return d >= clouds.period.start && d <= clouds.period.end; });
  console.log(`twilight hours: ${hours.length}, in the period: ${inPeriod.length}`);
  hours.length = 0; hours.push(...inPeriod);

  const listings = new Map();
  const listHour = async (bucket, ms) => {
    const d = new Date(ms);
    const doy = Math.floor((ms - Date.UTC(d.getUTCFullYear(), 0, 1)) / 86400e3) + 1;
    const prefix = `${acmRules.product}/${d.getUTCFullYear()}/${String(doy).padStart(3, '0')}/${String(d.getUTCHours()).padStart(2, '0')}/`;
    const k = `${bucket}/${prefix}`;
    if (!listings.has(k)) {
      const res = await fetch(`https://${bucket}.s3.amazonaws.com/?list-type=2&prefix=${encodeURIComponent(prefix)}`);
      if (!res.ok) throw new Error(`listing ${k}: HTTP ${res.status}`);
      const xml = await res.text();
      listings.set(k, [...xml.matchAll(/<Contents>([\s\S]*?)<\/Contents>/g)].map(([, c]) => {
        const key = /<Key>([^<]+)<\/Key>/.exec(c)[1];
        return { bucket, key, etag: /<ETag>([^<]+)<\/ETag>/.exec(c)[1].replace(/&quot;|"/g, ''), bytes: Number(/<Size>([^<]+)<\/Size>/.exec(c)[1]), ...scanTimes(key) };
      }));
    }
    return listings.get(k);
  };
  const satelliteFor = (ms) => {
    const day = new Date(ms).toISOString().slice(0, 10);
    return acmRules.satellites.find((x) => day >= x.from && day <= x.to);
  };
  const todo = [];
  let noScan = 0;
  for (const h of hours) {
    const sat = satelliteFor(h);
    const scans = [...(await listHour(sat.bucket, h - 10 * 60e3)), ...(await listHour(sat.bucket, h + 10 * 60e3))];
    let best = null;
    for (const s of scans) if (!best || Math.abs(s.midMs - h) < Math.abs(best.midMs - h)) best = s;
    if (best && Math.abs(best.midMs - h) <= acmRules.maxMatchMinutes * 60e3) todo.push({ ...best, hourMs: h }); else noScan++;
  }
  console.log(`scans: ${todo.length}, hours with no scan within ${acmRules.maxMatchMinutes} min: ${noScan}`);

  const partialPath = join(scratch, 'partial.json');
  const done = await access(partialPath).then(async () => JSON.parse(await readFile(partialPath)), () => ({}));
  const left = todo.filter((s) => !done[s.key]);
  console.log(`to fetch: ${left.length} (${(left.reduce((a, s) => a + s.bytes, 0) / 1e9).toFixed(2)} GB)`);
  let count = 0;
  await pool(left, async (s, w) => {
    const got = await download(s, w);
    done[s.key] = { hourMs: s.hourMs, bucket: s.bucket, key: s.key, etag: s.etag, bytes: s.bytes, sha256: got.sha256, midMs: s.midMs, boxes: got.boxes };
    if (++count % 50 === 0) { await writeFile(partialPath, JSON.stringify(done)); console.log(`${count} of ${left.length}`); }
  });
  await writeFile(partialPath, JSON.stringify(done));
  const scans = todo.map((s) => done[s.key]).sort((a, b) => a.hourMs - b.hourMs);
  await writeFile(OUT, JSON.stringify({
    about: 'Generated by scripts/fetch-goes-relative.js goes. One ACMC scan per twilight hour at JZI (nearest the whole hour): the S3 object, its SHA-256, and the 5 by 5 BCM and DQF box (row by row, north first; F is fill) at each airport and water point. Do not edit by hand.',
    fetched: new Date().toISOString(),
    twilightHours: hours.length,
    hoursWithNoScan: noScan,
    scans,
  }) + '\n');
  console.log(`wrote ${scans.length} scans`);
} else {
  throw new Error('usage: node scripts/fetch-goes-relative.js pixels <grid> | nbm | goes <scratch dir> [--recheck N]');
}
