// Satellite check, test 2: scores GOES Cloud Cover Layers low cloud against
// the airport sky below 10,000 ft. Reads only pinned files:
// data/goes/ccl-stations.json, data/goes/acm-stations.json (sample hours and
// scan times) and data/clouds/raw/. Rules: config/goes-ccl.json.
// Writes clouds/goes-ccl-results.json and clouds/goes-ccl-results.md.
//
//   node scripts/score-goes-ccl.js
import { readFile, writeFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { parseIemCsv, reportsByHour, reportCoverPct, sunElevationDeg, score } from './lib/clouds.js';

const root = new URL('../', import.meta.url);
const json = async (p) => JSON.parse(await readFile(new URL(p, root)));
const clouds = await json('config/cloud-stations.json');
const acmRules = await json('config/goes-acm.json');
const rules = await json('config/goes-ccl.json');
const acm = await json('data/goes/acm-stations.json');
const ccl = await json('data/goes/ccl-stations.json');
const manifest = await json('data/clouds/manifest.json');
const forecastResults = await json('clouds/results.json');
const raw = async (name) => {
  const buf = gunzipSync(await readFile(new URL(`data/clouds/raw/${name}`, root)));
  const sha = createHash('sha256').update(buf).digest('hex');
  if (sha !== manifest.files[name].sha256) throw new Error(`${name}: SHA-256 does not match the manifest`);
  return buf.toString('utf8');
};

const CLOUDY = clouds.cloudyPct;
const LOW_FT = 10000;
const byAcm = new Map(ccl.scans.map((s) => [s.acmKey, s]));
const satOf = (key) => /_G(\d+)_/.exec(key)[1];

const pairs = {}; // pairs[value][subset] = [[satellitePct, observedPct], ...]
const push = (value, sub, pair) => ((pairs[value] ??= {})[sub] ??= []).push(pair);
const dropped = { noReport: 0, noScan: 0, noCcl: 0, missingValue: 0, unknownCode: 0 };
const reports = {};
for (const id of Object.keys(clouds.stations)) reports[id] = reportsByHour(parseIemCsv(await raw(`${id}-iem.csv.gz`)));

for (const { kind, hourMs } of acm.hours) {
  for (const [id, st] of Object.entries(clouds.stations)) {
    const r = reports[id].get(hourMs);
    if (!r) { dropped.noReport++; continue; }
    let best = null;
    for (const s of acm.scans) if (!best || Math.abs(s.midMs - r.timeMs) < Math.abs(best.midMs - r.timeMs)) best = s;
    if (!best || Math.abs(best.midMs - r.timeMs) > acmRules.maxMatchMinutes * 60e3) { dropped.noScan++; continue; }
    const c = byAcm.get(best.key);
    if (!c) { dropped.noCcl++; continue; }
    const v = c.stations[id];
    // Missing rule (config/goes-ccl.json): values outside the valid ranges.
    if (!(v.TCF >= 0 && v.TCF <= 65530) || !(v.CF1 >= 0 && v.CF1 <= 100) || !(v.CF2 >= 0 && v.CF2 <= 100)) { dropped.missingValue++; continue; }
    const obs = reportCoverPct(r.layers, LOW_FT);
    if (obs == null) { dropped.unknownCode++; continue; }
    const low = Math.max(v.CF1, v.CF2);
    const upper = Math.min(v.TCF * c.tcfScale * 100, v.CF1 + v.CF2);
    const sun = sunElevationDeg(st, hourMs);
    const light = sun >= clouds.twilightSunDeg.min && sun <= clouds.twilightSunDeg.max ? 'twilight' : sun > clouds.twilightSunDeg.max ? 'day' : 'night';
    const sat = `G${satOf(best.key)}`;
    const subsets = ['all', light, sat, `${light}-${sat}`, `picked-${kind}`];
    if (clouds.nearCharleston.includes(id)) subsets.push('nearCharleston', `${light}-nearCharleston`);
    if (light === 'twilight') subsets.push(sun >= -3 ? 'twilight-sun0to3' : 'twilight-sun3to18');
    for (const sub of subsets) {
      push('maxCF1CF2', sub, [low, obs]);
      push('upperBound', sub, [upper, obs]);
    }
  }
}

const whole = (x) => (x == null ? null : Math.round(100 * x));
const results = {
  about: 'Generated by scripts/score-goes-ccl.js from data/goes/ccl-stations.json and data/clouds/raw. Do not edit by hand.',
  inputs: { cclScans: ccl.scans.length, hours: acm.hours.length, fetched: ccl.fetched },
  cloudyPct: CLOUDY,
  truth: rules.truth,
  dropped,
  tests: {},
};
for (const [value, subs] of Object.entries(pairs)) {
  results.tests[value] = {};
  for (const [sub, p] of Object.entries(subs).sort()) {
    const sc = score(p, CLOUDY);
    results.tests[value][sub] = { ...sc, skillPct: whole(sc.skill), hitPct: whole(sc.hitRate), falsePct: whole(sc.falseRate) };
  }
}
const g = rules.goNoGo;
const decisive = results.tests.maxCF1CF2[g.subset];
const hrrr = forecastResults.tests.layers.lowVsBelow10000ft.twilight.gfs_hrrr[0].skillPct;
results.goNoGo = {
  rule: `${g.value} against ${g.truth}, ${g.subset}: skill at least ${g.minSkillPct}`,
  skillPct: decisive?.skillPct ?? null,
  n: decisive?.n ?? 0,
  hrrrLowTwilightSkillPct: hrrr,
  pass: decisive?.skillPct != null && decisive.skillPct >= g.minSkillPct,
};
await writeFile(new URL('clouds/goes-ccl-results.json', root), JSON.stringify(results, null, 1) + '\n');

let md = `# GOES Cloud Cover Layers against airport reports (satellite check, test 2)\n\nGenerated by \`scripts/score-goes-ccl.js\`. Do not edit by hand. Method and reading: [README.md](README.md#satellite-check-test-2).\n\n`;
md += `${ccl.scans.length} CCL files for ${acm.hours.length} sample hours. Satellite value: max(CF1, CF2), the CCL cloud fraction below FL100 (lower bound), in the 10 km cell that holds the station. "upperBound" is min(TCF, CF1 + CF2), shown for reference. Truth: the airport sky below 10,000 ft. Cloudy means ${CLOUDY} percent or more for both. Skill is hit rate minus false-alarm rate. Pairs dropped: ${Object.entries(dropped).map(([k, n]) => `${k} ${n}`).join(', ')}.\n\n`;
md += `**Go/no-go** (${results.goNoGo.rule}): skill ${results.goNoGo.skillPct} on ${results.goNoGo.n} pairs, so **${results.goNoGo.pass ? 'go' : 'no-go'}**. HRRR low-cloud twilight skill against the same truth: ${hrrr}.\n`;
for (const [value, subs] of Object.entries(results.tests)) {
  md += `\n## Value: ${value}\n\n| Subset | Pairs | Airport cloudy | Skill | Hit rate | False-alarm rate | MAE |\n|---|---|---|---|---|---|---|\n`;
  for (const [sub, s] of Object.entries(subs)) md += `| ${sub} | ${s.n} | ${s.cloudy} | ${s.skillPct} | ${s.hitPct} | ${s.falsePct} | ${s.mae.toFixed(1)} |\n`;
}
await writeFile(new URL('clouds/goes-ccl-results.md', root), md);
console.log(md);
